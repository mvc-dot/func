#!/bin/bash
# One-time setup of the Cloudflare Tunnel that publishes the local strfry as wss://relay.func.rsvp.
# Prerequisite (needs a browser, once per machine): cloudflared tunnel login   → picks the func.rsvp zone
# Idempotent: re-running reuses the existing tunnel and rewrites the config and launchd service.
set -euo pipefail
NAME=func-relay
HOST=relay.func.rsvp
ORIGIN=http://127.0.0.1:7790
DIR="$(cd "$(dirname "$0")" && pwd)"
CFG=/Users/shan/.cloudflared/config.yml
PLIST=~/Library/LaunchAgents/rsvp.func.cloudflared.plist

[ -f ~/.cloudflared/cert.pem ] || { echo "Run 'cloudflared tunnel login' first (choose func.rsvp)."; exit 1; }

ID=$(cloudflared tunnel list --name "$NAME" --output json | python3 -c 'import sys,json; r=json.load(sys.stdin); print(r[0]["id"] if r else "")')
if [ -z "$ID" ]; then
  cloudflared tunnel create "$NAME" >/dev/null
  ID=$(cloudflared tunnel list --name "$NAME" --output json | python3 -c 'import sys,json; print(json.load(sys.stdin)[0]["id"])')
fi
echo "tunnel $NAME = $ID"

cat > "$CFG" <<EOF
# Generated by relay/tunnel-setup.sh
tunnel: $ID
credentials-file: /Users/shan/.cloudflared/$ID.json
protocol: http2
ingress:
  - hostname: $HOST
    service: $ORIGIN
    originRequest:
      noTLSVerify: true
  - service: http_status:404
EOF

# CNAME relay.func.rsvp -> <id>.cfargotunnel.com (no-op if it already exists)
cloudflared tunnel route dns --overwrite-dns "$NAME" "$HOST" || true

sed "s|__CONFIG__|$CFG|" "$DIR/launchd/rsvp.func.cloudflared.plist" > "$PLIST"
launchctl bootout "gui/$(id -u)/rsvp.func.cloudflared" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
sleep 4
launchctl print "gui/$(id -u)/rsvp.func.cloudflared" | grep -E "state|pid" | head -2
echo "NIP-11 via tunnel:"; curl -s --max-time 15 -H "Accept: application/nostr+json" "https://$HOST/" | head -c 200; echo
